"""SLIP-39 interop between our JS wrapper (packages/core/src/backup.ts) and Trezor's Python
reference (shamir-mnemonic). The official vectors are tested on the JS side (npm test).

Usage (from this folder): .venv/Scripts/python check.py   (Windows)
                          .venv/bin/python check.py       (macOS, Linux)
"""

import json
import os
import shutil
import subprocess
import sys

import shamir_mnemonic

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
# Our configuration: group threshold 2, CLIENT and PARTNER ("tiers") groups of 1 share each.
GROUP_THRESHOLD = 2
GROUPS = [(1, 1), (1, 1)]


def js(request):
    npx = shutil.which("npx") or shutil.which("npx.cmd")
    out = subprocess.run(
        [npx, "tsx", os.path.join(HERE, "js-side.ts")],
        input=json.dumps(request),
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=True,
    )
    return json.loads(out.stdout.strip().splitlines()[-1])


def check(label, ok):
    print(("OK    " if ok else "FAIL  ") + label)
    return ok


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    results = []

    # 1. Shares generated by JS, restored by the Python reference.
    split = js({"op": "split"})
    restored = shamir_mnemonic.combine_mnemonics([split["client"], split["tiers"]]).hex()
    results.append(check("JS -> Python: CLIENT + PARTNER restore the secret", restored == split["secret"]))
    try:
        shamir_mnemonic.combine_mnemonics([split["tiers"]])
        results.append(check("JS -> Python: PARTNER alone is refused", False))
    except shamir_mnemonic.MnemonicError:
        results.append(check("JS -> Python: PARTNER alone is refused", True))

    # 2. Shares generated by the Python reference, restored by JS.
    secret = os.urandom(16)
    groups = shamir_mnemonic.generate_mnemonics(GROUP_THRESHOLD, GROUPS, secret)
    client, tiers = groups[0][0], groups[1][0]
    out = js({"op": "combine", "mnemonics": [client, tiers]})
    results.append(check("Python -> JS: CLIENT + PARTNER restore the secret", out.get("secret") == secret.hex()))
    out = js({"op": "combine", "mnemonics": [client]})
    results.append(check("Python -> JS: CLIENT alone is refused", "error" in out))

    print()
    if all(results):
        print("SLIP-39 interop validated.")
        return 0
    print("SLIP-39 interop failed.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
